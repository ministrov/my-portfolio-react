/**
 * Полная перезагрузка вкладки — отдельным модулем, чтобы тесты подменяли её
 * через `vi.mock`: в jsdom `location.reload` не работает и не подменяется.
 *
 * Аргументы намеренно не принимает: обработчик клика передал бы событие, а
 * Firefox читает первый аргумент `reload()` как «мимо кеша».
 *
 * @module errorBoundary/reloadPage
 */

/** Перезагружает текущую страницу. */
export const reloadPage = () => {
  window.location.reload();
};
